SEASONS = sa.table(
    "tariff_seasons",
    sa.column("tariff_name", sa.String),
    sa.column("rate_plan", sa.String),
    sa.column("start_date", sa.Date),
    sa.column("end_date", sa.Date),
    sa.column("nightly_rate", sa.Numeric(10, 2)),
)


def _rows():
    for tariff_name, seasons in HISTORY:
        for start, end, rate in seasons:
            yield tariff_name, date.fromisoformat(start), date.fromisoformat(end), Decimal(rate)


def _sa(name: str):
    return sa.and_(SEASONS.c.tariff_name == name, SEASONS.c.rate_plan == "SA")


def _set_rate(start: date, name: str, current: Decimal, new: Decimal) -> None:
    op.get_bind().execute(
        SEASONS.update()
        .where(_sa(name), SEASONS.c.start_date == start, SEASONS.c.nightly_rate == current)
        .values(nightly_rate=new)
    )


def upgrade() -> None:
    connection = op.get_bind()
    for name, start, end, rate in _rows():
        # Never overwrite a season already in Tarifas.
        overlapping = connection.execute(
            sa.select(SEASONS.c.start_date).where(
                _sa(name), SEASONS.c.start_date <= end, SEASONS.c.end_date >= start
            )
        ).first()
        if overlapping:
            continue
        connection.execute(
            SEASONS.insert().values(
                tariff_name=name, rate_plan="SA", start_date=start, end_date=end,
                nightly_rate=rate,
            )
        )
    name, start, loaded, avantio = CORRECTION
    _set_rate(start, name, loaded, avantio)


def downgrade() -> None:
    connection = op.get_bind()
    name, start, loaded, avantio = CORRECTION
    _set_rate(start, name, avantio, loaded)
    for name, start, end, rate in _rows():
        if end < FIRST_LOADED_DAY:
            connection.execute(
                SEASONS.delete().where(
                    _sa(name),
                    SEASONS.c.start_date == start,
                    SEASONS.c.end_date == end,
                    SEASONS.c.nightly_rate == rate,
                )
            )
